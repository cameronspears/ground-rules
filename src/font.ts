export const GLYPH_W = 5, GLYPH_H = 7;

export function textWidth(s: string, scale = 1) { return s.length ? (s.length * (GLYPH_W + 1) - 1) * scale : 0; }

// Draw text at (x, y) top-left. `shadow` draws a 1-pixel drop shadow first.
export function text(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, color: string, scale = 1, shadow?: string) {
  if (shadow) text(ctx, s, x + scale, y + scale, shadow, scale);
  ctx.fillStyle = color;
  let cx = Math.round(x);
  for (const ch of s.toUpperCase()) {
    const g = G[ch] ?? G['?'];
    for (let i = 0; i < 35; i++) if (g[i] === '#') ctx.fillRect(cx + (i % 5) * scale, Math.round(y) + Math.floor(i / 5) * scale, scale, scale);
    cx += (GLYPH_W + 1) * scale;
  }
}
